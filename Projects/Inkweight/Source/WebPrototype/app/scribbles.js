function place(art) {
  const cells = new Array(W * H);
  for (let i = 0; i < W * H; i++) cells[i] = 0;
  const h = art.length;
  const w = art[0].length;
  const ox = Math.floor((W - w) / 2);
  const oy = Math.floor((H - h) / 2);
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const ch = art[y].charCodeAt(x) - 48;
      if (ch >= 1 && ch <= 4) cells[(oy + y) * W + ox + x] = ch;
    }
  }
  return cells;
}

